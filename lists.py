# Python Lists

students = ["Arun", "Priya", "Kumar", "Divya"]

print("Student List:", students)

# Add a student
students.append("Rahul")
print("After Adding:", students)

# Remove a student
students.remove("Kumar")
print("After Removing:", students)

# Display each student
print("Student Names:")

for student in students:
    print(student)
